import { useEffect, useMemo, useState } from "react";
import {
  AlertTriangle,
  Check,
  CheckCircle2,
  Copy,
  Download,
  Info,
  ShieldAlert,
  Wand2,
} from "lucide-react";
import { ALL_PINS, LEFT_PINS, PERIPHERAL_MODULES, RIGHT_PINS } from "../data/pinout";
import type { Translations } from "../i18n";
import type { PinDef } from "../types";

interface PinoutViewProps {
  t: Translations;
  initialPinId?: string | null;
  focusNonce?: number;
  onPinChange?: (pin: PinDef) => void;
}

interface PinConflict {
  severity: "error" | "warn";
  gpio: number;
  title: string;
  detail: string;
}

export function PinoutView({ t, initialPinId, focusNonce, onPinChange }: PinoutViewProps) {
  const [filter, setFilter] = useState("all");
  const [selectedPin, setSelectedPin] = useState<PinDef>(
    () => ALL_PINS.find((p) => p.id === initialPinId) ?? RIGHT_PINS[13],
  );
  const [enabledModules, setEnabledModules] = useState<string[]>(["oled", "rgb"]);
  const [rfidResetRemapped, setRfidResetRemapped] = useState(false);
  const [copied, setCopied] = useState(false);

  const selectPin = (pin: PinDef) => {
    setSelectedPin(pin);
    onPinChange?.(pin);
  };

  useEffect(() => {
    if (initialPinId) {
      const found = ALL_PINS.find((p) => p.id === initialPinId);
      if (found) {
        setFilter("all");
        setSelectedPin(found);
      }
    }
  }, [initialPinId, focusNonce]);

  const filters = [
    { id: "all", label: t.filterAll },
    { id: "power", label: "Power" },
    { id: "strapping", label: "Strapping" },
    { id: "adc", label: "ADC" },
    { id: "spi", label: "SPI" },
    { id: "i2c", label: "I2C" },
    { id: "i2s", label: "I2S" },
    { id: "uart", label: "UART" },
    { id: "touch", label: "Touch" },
    { id: "usb", label: "USB" },
    { id: "psram", label: "PSRAM" },
  ];

  const effectiveModules = useMemo(
    () =>
      PERIPHERAL_MODULES.map((mod) =>
        mod.id === "rfid" && rfidResetRemapped
          ? {
              ...mod,
              pins: mod.pins.map((p) => (p.role === "RFID_RST" ? { ...p, gpio: 21 } : p)),
            }
          : mod,
      ),
    [rfidResetRemapped],
  );

  const pinAssignments = useMemo(() => {
    const map: Record<number, { module: string; role: string; color: string }[]> = {};
    effectiveModules
      .filter((m) => enabledModules.includes(m.id))
      .forEach((mod) => {
        mod.pins.forEach((p) => {
          if (!map[p.gpio]) map[p.gpio] = [];
          map[p.gpio].push({ module: mod.name, role: p.role, color: mod.color });
        });
      });
    return map;
  }, [effectiveModules, enabledModules]);

  const conflicts = useMemo<PinConflict[]>(() => {
    const issues: PinConflict[] = [];
    Object.entries(pinAssignments).forEach(([gpioStr, list]) => {
      const gpio = Number(gpioStr);
      if (list.length > 1) {
        issues.push({
          severity: "error",
          gpio,
          title: `GPIO${gpio} Pin Collision`,
          detail: `Shared by ${list.map((x) => `${x.role} (${x.module})`).join(" & ")}`,
        });
      }
      const pinObj = ALL_PINS.find((p) => p.gpio === gpio);
      if (pinObj?.types.includes("psram")) {
        issues.push({
          severity: "error",
          gpio,
          title: `GPIO${gpio} Octal PSRAM Hazard`,
          detail: `Assigned to ${list[0].role}, but GPIO35–37 are reserved for Octal PSRAM on N8R8/N16R8 boards.`,
        });
      }
      if (pinObj?.types.includes("strapping")) {
        issues.push({
          severity: "warn",
          gpio,
          title: `GPIO${gpio} Strapping Pin Warning`,
          detail: `${list[0].role} uses a boot strapping pin (${pinObj.strapping}).`,
        });
      }
    });
    return issues;
  }, [pinAssignments]);

  const hasGpio9Collision = conflicts.some((c) => c.gpio === 9 && c.severity === "error");

  const generatedHeader = useMemo(() => {
    const lines = ["// Auto-generated by ESP-Labs Studio", "#pragma once", ""];
    effectiveModules
      .filter((m) => enabledModules.includes(m.id))
      .forEach((mod) => {
        lines.push(`// ${mod.name}`);
        mod.pins.forEach((p) => {
          lines.push(`#define PIN_${p.role.padEnd(14)} ${p.gpio}`);
        });
        lines.push("");
      });
    return lines.join("\n");
  }, [effectiveModules, enabledModules]);

  const copyHeader = () => {
    void navigator.clipboard?.writeText(generatedHeader);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1800);
  };

  const downloadHeader = () => {
    const blob = new Blob([generatedHeader], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "pins_config.h";
    a.click();
    URL.revokeObjectURL(url);
  };

  const toggleModule = (id: string) => {
    setEnabledModules((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id],
    );
  };

  const getPinDotColor = (pin: PinDef) => {
    if (pin.gpio !== null && pinAssignments[pin.gpio]) {
      if (pinAssignments[pin.gpio].length > 1 || pin.types.includes("psram")) return "#f43f5e";
      return pinAssignments[pin.gpio][0].color;
    }
    if (pin.types.includes("power")) return pin.label === "GND" ? "#64748b" : "#f59e0b";
    if (pin.types.includes("strapping")) return "#fb923c";
    if (pin.types.includes("psram")) return "#f43f5e";
    if (pin.types.includes("usb")) return "#38bdf8";
    return "#22d3ee";
  };

  const selectedAssignments =
    selectedPin.gpio !== null ? pinAssignments[selectedPin.gpio] ?? [] : [];

  return (
    <div className="space-y-5">
      {/* Signal Filter Bar */}
      <div className="flex flex-wrap gap-1.5">
        {filters.map((f) => (
          <button
            type="button"
            key={f.id}
            onClick={() => setFilter(f.id)}
            className={`px-3 py-1.5 rounded-lg text-xs font-mono font-semibold border transition-colors cursor-pointer whitespace-nowrap ${
              filter === f.id
                ? "bg-cyan-600 dark:bg-cyan-500 text-white dark:text-slate-950 border-cyan-600 dark:border-cyan-400"
                : "bg-white dark:bg-slate-900 border-slate-200 dark:border-slate-800 text-slate-700 dark:text-slate-300 hover:border-slate-400"
            }`}
          >
            {f.label}
          </button>
        ))}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5 items-start">
        {/* Interactive 44-Pin ESP32-S3-DevKitC-1 SVG Board */}
        <div className="lg:col-span-6 p-4 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900/70 flex justify-center">
          <svg viewBox="0 0 420 560" className="w-full max-w-[420px] h-auto select-none">
            {/* PCB Base */}
            <rect x="95" y="18" width="230" height="524" rx="14" fill="#0f172a" stroke="#334155" strokeWidth="2.5" />
            {/* WROOM-1 Metal Shield */}
            <rect x="135" y="34" width="150" height="145" rx="6" fill="#1e293b" stroke="#475569" strokeWidth="1.5" />
            <rect x="135" y="20" width="150" height="22" rx="3" fill="#0b1120" stroke="#334155" />
            <text x="210" y="34" textAnchor="middle" fill="#94a3b8" fontSize="8" fontFamily="IBM Plex Mono, monospace">
              2.4GHz PCB ANTENNA
            </text>
            <text x="210" y="96" textAnchor="middle" fill="#e2e8f0" fontSize="13" fontWeight="bold" fontFamily="IBM Plex Mono, monospace">
              ESP32-S3
            </text>
            <text x="210" y="114" textAnchor="middle" fill="#22d3ee" fontSize="9.5" fontFamily="IBM Plex Mono, monospace">
              WROOM-1 N16R8
            </text>
            <text x="210" y="132" textAnchor="middle" fill="#94a3b8" fontSize="8" fontFamily="IBM Plex Mono, monospace">
              Wi-Fi + BLE 5.0
            </text>

            {/* Onboard WS2812 RGB LED */}
            <circle
              cx="264"
              cy="435"
              r="7"
              fill={enabledModules.includes("rgb") ? "#10b981" : "#334155"}
              stroke="#94a3b8"
              strokeWidth="1.5"
            />
            <text x="264" y="454" textAnchor="middle" fill="#94a3b8" fontSize="7.5" fontFamily="IBM Plex Mono, monospace">
              RGB48
            </text>

            {/* RST & BOOT Buttons */}
            <rect x="148" y="445" width="32" height="18" rx="3" fill="#1e293b" stroke="#64748b" />
            <text x="164" y="457" textAnchor="middle" fill="#cbd5e1" fontSize="8" fontFamily="IBM Plex Mono, monospace">
              RST
            </text>
            <rect x="240" y="445" width="32" height="18" rx="3" fill="#1e293b" stroke="#f59e0b" />
            <text x="256" y="457" textAnchor="middle" fill="#fbbf24" fontSize="8" fontFamily="IBM Plex Mono, monospace">
              BOOT
            </text>

            {/* Dual USB-C Ports */}
            <rect x="138" y="514" width="46" height="32" rx="4" fill="#334155" stroke="#94a3b8" strokeWidth="1.5" />
            <text x="161" y="533" textAnchor="middle" fill="#e2e8f0" fontSize="7.5" fontFamily="IBM Plex Mono, monospace">
              USB-OTG
            </text>
            <rect x="236" y="514" width="46" height="32" rx="4" fill="#334155" stroke="#94a3b8" strokeWidth="1.5" />
            <text x="259" y="533" textAnchor="middle" fill="#e2e8f0" fontSize="7.5" fontFamily="IBM Plex Mono, monospace">
              UART
            </text>

            {/* Left Header Pins (22) */}
            {LEFT_PINS.map((pin, idx) => {
              const y = 44 + idx * 21.5;
              const matches = filter === "all" || pin.types.includes(filter);
              const isSelected = selectedPin.id === pin.id;
              const assigned = pin.gpio !== null ? pinAssignments[pin.gpio] : undefined;
              const isConflict = Boolean(assigned && (assigned.length > 1 || pin.types.includes("psram")));
              const dotColor = getPinDotColor(pin);

              return (
                <g
                  key={pin.id}
                  onClick={() => selectPin(pin)}
                  style={{ opacity: matches ? 1 : 0.22, cursor: "pointer" }}
                >
                  <rect
                    x="10"
                    y={y - 8}
                    width="76"
                    height="16"
                    rx="4"
                    fill={isSelected ? "#0891b2" : isConflict ? "#be123c" : assigned ? "#1e293b" : "#0b1120"}
                    stroke={isSelected ? "#22d3ee" : isConflict ? "#fb7185" : assigned ? dotColor : "#334155"}
                    strokeWidth={isSelected || isConflict ? 1.5 : 1}
                  />
                  <text
                    x="80"
                    y={y + 3.5}
                    textAnchor="end"
                    fill={isSelected ? "#ffffff" : "#e2e8f0"}
                    fontSize="9.5"
                    fontFamily="IBM Plex Mono, monospace"
                    fontWeight="600"
                  >
                    {pin.label}
                  </text>
                  <line x1="86" y1={y} x2="108" y2={y} stroke={dotColor} strokeWidth="1.5" />
                  <circle cx="112" cy={y} r={isSelected ? 5.5 : 4.2} fill={dotColor} stroke="#0f172a" strokeWidth="1.5" />
                </g>
              );
            })}

            {/* Right Header Pins (22) */}
            {RIGHT_PINS.map((pin, idx) => {
              const y = 44 + idx * 21.5;
              const matches = filter === "all" || pin.types.includes(filter);
              const isSelected = selectedPin.id === pin.id;
              const assigned = pin.gpio !== null ? pinAssignments[pin.gpio] : undefined;
              const isConflict = Boolean(assigned && (assigned.length > 1 || pin.types.includes("psram")));
              const dotColor = getPinDotColor(pin);

              return (
                <g
                  key={pin.id}
                  onClick={() => selectPin(pin)}
                  style={{ opacity: matches ? 1 : 0.22, cursor: "pointer" }}
                >
                  <circle cx="308" cy={y} r={isSelected ? 5.5 : 4.2} fill={dotColor} stroke="#0f172a" strokeWidth="1.5" />
                  <line x1="312" y1={y} x2="334" y2={y} stroke={dotColor} strokeWidth="1.5" />
                  <rect
                    x="334"
                    y={y - 8}
                    width="76"
                    height="16"
                    rx="4"
                    fill={isSelected ? "#0891b2" : isConflict ? "#be123c" : assigned ? "#1e293b" : "#0b1120"}
                    stroke={isSelected ? "#22d3ee" : isConflict ? "#fb7185" : assigned ? dotColor : "#334155"}
                    strokeWidth={isSelected || isConflict ? 1.5 : 1}
                  />
                  <text
                    x="340"
                    y={y + 3.5}
                    textAnchor="start"
                    fill={isSelected ? "#ffffff" : "#e2e8f0"}
                    fontSize="9.5"
                    fontFamily="IBM Plex Mono, monospace"
                    fontWeight="600"
                  >
                    {pin.label}
                  </text>
                </g>
              );
            })}
          </svg>
        </div>

        {/* Right Side: Pin Inspector + Conflict Checker */}
        <div className="lg:col-span-6 space-y-5">
          {/* Pin Inspector */}
          <div className="p-5 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900/70 space-y-3">
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-semibold flex items-center gap-2">
                <Info className="w-4 h-4 text-cyan-500" />
                {t.pinInspector}
              </h3>
              <span className="font-mono text-sm font-bold text-cyan-600 dark:text-cyan-400">
                {selectedPin.label}
              </span>
            </div>

            <div className="text-xs font-mono text-slate-500 dark:text-slate-400 flex flex-wrap gap-x-2 gap-y-1">
              <span>{selectedPin.types.map((tp) => tp.toUpperCase()).join(" · ")}</span>
              {selectedPin.adc && (
                <>
                  <span aria-hidden="true">/</span>
                  <span className="text-sky-600 dark:text-sky-400">{selectedPin.adc}</span>
                </>
              )}
              {selectedPin.touch && (
                <>
                  <span aria-hidden="true">/</span>
                  <span className="text-violet-600 dark:text-violet-400">{selectedPin.touch}</span>
                </>
              )}
            </div>

            <p className="text-sm text-slate-700 dark:text-slate-300">{selectedPin.notes}</p>

            {selectedAssignments.length > 0 && (
              <div className="p-2.5 rounded-lg bg-slate-50 dark:bg-slate-950/70 border border-slate-200 dark:border-slate-800 text-xs font-mono">
                <span className="text-slate-500 mr-2">Active assignment:</span>
                {selectedAssignments.map((a, idx) => (
                  <span key={a.role} className="text-cyan-600 dark:text-cyan-300 font-semibold">
                    {idx > 0 ? " + " : ""}
                    {a.role} ({a.module})
                  </span>
                ))}
              </div>
            )}

            {selectedPin.strapping && (
              <div className="p-3 rounded-lg bg-amber-500/10 border border-amber-500/30 text-xs text-amber-800 dark:text-amber-300">
                <span className="font-semibold">Strapping Behavior: </span>
                {selectedPin.strapping}
              </div>
            )}

            {selectedPin.gotcha && (
              <div className="p-3 rounded-lg bg-rose-500/10 border border-rose-500/30 text-xs text-rose-700 dark:text-rose-300 flex gap-2">
                <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5" />
                <div>
                  <span className="font-semibold">Hardware Gotcha: </span>
                  {selectedPin.gotcha}
                </div>
              </div>
            )}
          </div>

          {/* Module Conflict Checker */}
          <div className="p-5 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900/70 space-y-4">
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-semibold flex items-center gap-2">
                <ShieldAlert className="w-4 h-4 text-amber-500" />
                {t.conflictChecker}
              </h3>
              <span
                className={`text-xs font-mono font-semibold ${
                  conflicts.length > 0
                    ? "text-rose-600 dark:text-rose-400"
                    : "text-emerald-600 dark:text-emerald-400"
                }`}
              >
                {conflicts.length > 0 ? `▲ ${conflicts.length} Issue(s)` : "● Nominal"}
              </span>
            </div>

            <div className="flex flex-wrap gap-2">
              {effectiveModules.map((mod) => {
                const active = enabledModules.includes(mod.id);
                return (
                  <button
                    type="button"
                    key={mod.id}
                    onClick={() => toggleModule(mod.id)}
                    className={`flex items-center gap-2 px-3 py-1.5 rounded-lg text-xs font-semibold border transition-colors cursor-pointer ${
                      active
                        ? "bg-slate-900 dark:bg-slate-800 border-cyan-500 text-white"
                        : "bg-slate-50 dark:bg-slate-950/60 border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400 hover:border-slate-400"
                    }`}
                  >
                    <span className="w-2.5 h-2.5 rounded-full" style={{ backgroundColor: mod.color }} />
                    {mod.name}
                  </button>
                );
              })}
            </div>

            {/* Auto-Resolve Action for GPIO9 Collision */}
            {(hasGpio9Collision || rfidResetRemapped) && (
              <div className="flex items-center gap-2">
                {hasGpio9Collision && (
                  <button
                    type="button"
                    onClick={() => setRfidResetRemapped(true)}
                    className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-amber-500 hover:bg-amber-400 text-slate-950 cursor-pointer"
                  >
                    <Wand2 className="w-3.5 h-3.5" />
                    {t.autoResolve}
                  </button>
                )}
                {rfidResetRemapped && (
                  <button
                    type="button"
                    onClick={() => setRfidResetRemapped(false)}
                    className="px-3 py-1.5 rounded-lg text-xs font-medium border border-slate-300 dark:border-slate-700 hover:border-cyan-500 cursor-pointer"
                  >
                    {t.restoreDefaultPins}
                  </button>
                )}
              </div>
            )}

            {/* Conflict Alerts */}
            {conflicts.length > 0 ? (
              <div className="space-y-2">
                {conflicts.map((c, idx) => (
                  <div
                    key={idx}
                    className={`p-3 rounded-lg border text-xs flex gap-2 ${
                      c.severity === "error"
                        ? "bg-rose-500/10 border-rose-500/40 text-rose-700 dark:text-rose-300"
                        : "bg-amber-500/10 border-amber-500/40 text-amber-800 dark:text-amber-300"
                    }`}
                  >
                    <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5" />
                    <div>
                      <div className="font-bold font-mono">{c.title}</div>
                      <div>{c.detail}</div>
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <div className="p-3 rounded-lg bg-emerald-500/10 border border-emerald-500/30 text-xs text-emerald-700 dark:text-emerald-300 flex items-center gap-2">
                <CheckCircle2 className="w-4 h-4 shrink-0" />
                <span>
                  {t.noConflicts} — {t.cleanAssignments}
                </span>
              </div>
            )}

            {/* Generated pins_config.h */}
            <div>
              <div className="flex flex-wrap items-center justify-between gap-2 mb-1.5">
                <span className="text-xs font-mono text-slate-500 dark:text-slate-400">
                  pins_config.h
                </span>
                <div className="flex items-center gap-1.5">
                  <button
                    type="button"
                    onClick={downloadHeader}
                    className="flex items-center gap-1 px-2.5 py-1 rounded-lg border border-slate-200 dark:border-slate-700 text-xs font-medium hover:border-cyan-500 cursor-pointer"
                  >
                    <Download className="w-3.5 h-3.5" />
                    {t.downloadHeader}
                  </button>
                  <button
                    type="button"
                    onClick={copyHeader}
                    className="flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-cyan-500/15 hover:bg-cyan-500/25 text-cyan-700 dark:text-cyan-300 text-xs font-semibold cursor-pointer"
                  >
                    {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                    {copied ? t.copied : t.copyHeader}
                  </button>
                </div>
              </div>
              <pre className="workbench-scroll p-3 rounded-lg bg-[#060a12] border border-slate-800 text-xs font-mono text-emerald-300 overflow-x-auto max-h-48">
                {generatedHeader}
              </pre>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
